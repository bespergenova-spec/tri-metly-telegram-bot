// Когда включать рассуждение модели (параметр OpenRouter reasoning.effort).
// Включаем только там, где надо проверить несколько правил или посчитать: бронь и расчёты.
// Простые вопросы (меню, цена одной позиции, адрес, график, квиз) идут без рассуждения.

export const EFFORT_ON = 'high';
export const EFFORT_OFF = 'none';

// \b в JavaScript не работает с кириллицей, поэтому границы слов заданы явно.
const BOOKING = [
  /брон|заяв|столик|резерв|опозда/i,
  /\d+\s*(человек|гост|персон)/i,
  /нас\s+(будет\s+)?(\d+|двое|трое|четверо|пятеро|шестеро|семеро)/i,
  /(двое|трое|четверо|пятеро|шестеро|семеро)\s+(человек|гост)|компани[яюией]/i,
  /(прийти|прид[её]м|приду|при[её]дем)[^.?!]*\d{1,2}[:.]\d{2}/i,
  /\b(book|booking|reserve|reservation|table)\b/i,
  /брондау|үстел/i,
];

const CALCULATION = [
  /посчита|подсчита|сосчита|рассчита|расч[её]т|итого|скидк/i,
  /(^|[^а-яё])сч[её]т(а|у|ом|е)?($|[^а-яё])/i, // «счёт», но не «насчёт»
  /сколько\s+(всего|вместе|получится|выйдет|будет стоить|с нас|с меня)|всего\s+сколько|в сумме|обойд[её]тся/i,
  // «сколько» и количество позиций: «2 пива», «два пирога»
  /сколько[\s\S]*(^|[^а-яё\d])(\d+|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять)\s+[а-яё]/i,
  /(^|[^а-яё\d])(\d+|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять)\s+[а-яё][\s\S]*сколько/i,
  /добав(ь|ьте|им)?\s+ещ[её]|\d\s*\+\s*\d/i,
  /\b(total|discount)\b/i,
  /барлығы|жеңілдік/i,
];

export function needsReasoning(text) {
  const t = String(text ?? '');
  return [...BOOKING, ...CALCULATION].some((re) => re.test(t));
}

export function effortFor(text) {
  return needsReasoning(text) ? EFFORT_ON : EFFORT_OFF;
}
